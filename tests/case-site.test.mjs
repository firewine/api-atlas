import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cp, mkdtemp, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { stripVTControlCharacters } from 'node:util';
import { caseRecipe, codeSnapshot, docSnapshot } from './fixtures/case-recipe.mjs';

test('isolated generated case builds static HTML, linked profiles and sitemap; build checks reject mutations', async () => {
  const root = await mkdtemp(join(tmpdir(), 'atlas-case-site-'));
  const repo = fileURLToPath(new URL('../', import.meta.url));
  const env = { ...process.env, SITE_URL: 'https://getbeta.app', BASE_PATH: '/api-atlas/', ASTRO_TELEMETRY_DISABLED: '1' };
  const run = (script, args = []) => {
    const result = spawnSync(process.execPath, [join(root, script), ...args], { cwd: root, env, encoding: 'utf8', timeout: 60000 });
    assert.ifError(result.error);
    return { status: result.status, output: stripVTControlCharacters(result.stdout + result.stderr) };
  };
  try {
    for (const path of ['src', 'public', 'scripts', 'package.json', 'astro.config.mjs', 'tsconfig.json']) await cp(join(repo, path), join(root, path), { recursive: true });
    await cp(join(repo, 'case-studies/evidence'), join(root, 'case-studies/evidence'), { recursive: true });
    await symlink(join(repo, 'node_modules'), join(root, 'node_modules'), 'junction');
    await writeFile(join(root, 'case-studies/evidence/fixture-code.txt'), codeSnapshot);
    await writeFile(join(root, 'case-studies/evidence/fixture-doc.txt'), docSnapshot);
    const inputPath = join(root, 'recipe.json');
    await writeFile(inputPath, JSON.stringify(caseRecipe()));
    const generation = run('scripts/generate-case-study.mjs', [inputPath]);
    assert.equal(generation.status, 0, generation.output);
    const generated = join(root, 'src/data/guides/fixture-empty-page.md');
    const astroPackage = JSON.parse(await readFile(join(root, 'node_modules/astro/package.json'), 'utf8'));
    const cli = `node_modules/astro/${astroPackage.bin.astro}`;
    const build = run(cli, ['build']);
    assert.equal(build.status, 0, build.output);
    const pagefindPackage = JSON.parse(await readFile(join(root, 'node_modules/pagefind/package.json'), 'utf8'));
    const pagefindCli = typeof pagefindPackage.bin === 'string' ? pagefindPackage.bin : pagefindPackage.bin.pagefind;
    const search = run(`node_modules/pagefind/${pagefindCli}`, ['--site', 'dist']);
    assert.equal(search.status, 0, search.output);
    const distribution = run('scripts/verify-dist.mjs');
    assert.equal(distribution.status, 0, distribution.output);
    const valid = run('scripts/validate-guides.mjs');
    assert.equal(valid.status, 0, valid.output);
    assert.match(valid.output, /10 guides, 3 reviewed cases/);
    const built = join(root, 'dist/guides/fixture-empty-page/index.html');
    const html = await readFile(built, 'utf8');
    assert.match(html, /<h1[^>]*>Fixture API 빈 페이지 누락: empty_page 감지<\/h1>/);
    const invalidCanonical = html.replace('rel="canonical"', 'rel="wrong-canonical"');
    await writeFile(built, invalidCanonical);
    const rejected = run('scripts/validate-guides.mjs');
    assert.equal(rejected.status, 1, rejected.output);
    assert.match(rejected.output, /canonical/);
    await writeFile(built, html);
    const provider = join(root, 'dist/apis/openai/index.html');
    const profile = await readFile(provider, 'utf8');
    await writeFile(provider, profile.replace('href="/api-atlas/guides/fixture-empty-page/"', 'href="/guides/fixture-empty-page/"'));
    const brokenLink = run('scripts/validate-guides.mjs');
    assert.equal(brokenLink.status, 1, brokenLink.output);
    assert.match(brokenLink.output, /Missing descriptive backlink/);
    await writeFile(provider, profile);
    const sitemap = join(root, 'dist/sitemap.xml');
    const xml = await readFile(sitemap, 'utf8');
    await writeFile(sitemap, xml.replace(/<url>\s*<loc>https:\/\/getbeta.app\/api-atlas\/guides\/fixture-empty-page\/[\s\S]*?<\/url>/, ''));
    const noSitemap = run('scripts/validate-guides.mjs');
    assert.equal(noSitemap.status, 1, noSitemap.output);
    assert.match(noSitemap.output, /sitemap entry/);
    await writeFile(sitemap, xml);
    await writeFile(built, html.replace('href="/api-atlas/apis/openai/"', 'href="/api-atlas/apis/missing-provider/"'));
    const missingTarget = run('scripts/verify-dist.mjs');
    assert.equal(missingTarget.status, 1, missingTarget.output);
    assert.match(missingTarget.output, /broken internal URL \/api-atlas\/apis\/missing-provider\//);
    await writeFile(built, html.replace('href="/api-atlas/apis/openai/"', 'href="/api-atlas/apis/openai/#missing-field"'));
    const missingAnchor = run('scripts/verify-dist.mjs');
    assert.equal(missingAnchor.status, 1, missingAnchor.output);
    assert.match(missingAnchor.output, /broken internal anchor/);
    const source = await readFile(generated, 'utf8');
    const invalid = source.replace('"h1": "Fixture API 빈 페이지 누락: empty_page 감지"', '"h1": "Unrelated keywords"');
    assert.notEqual(invalid, source);
    await writeFile(generated, invalid);
    const invalidSource = run(cli, ['sync']);
    assert.equal(invalidSource.status, 1, invalidSource.output);
    assert.match(invalidSource.output, /Case requires description and matching title\/H1/);
  } finally { await rm(root, { recursive: true, force: true }); }
});
